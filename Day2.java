public class BiodataDiri {
    public static void main(String[] args) {

        // println() untuk menampilkan teks dan pindah baris
        System.out.println("=== BIODATA DIRI ===");
        System.out.println("Nama: Muh Rizky Alfajri");

        // print() untuk menampilkan teks tanpa pindah baris
        System.out.print("Umur: ");
        System.out.print("18 tahun\n");

        // printf() untuk menampilkan teks dengan format
        System.out.printf("Alamat: %s%n", "Kalukku");
        System.out.printf("Status: %s%n", "Mahasiswa");
        System.out.printf("Jenis Kelamin: %s%n", "Laki-laki");
    }
}
